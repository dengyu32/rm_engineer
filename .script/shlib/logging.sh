#!/bin/bash
# ==============================================================================
# 脚本名称: logging.sh
# 描述: 负责后台日志文件的页眉/页脚记录，用于审计节点运行状态和退出原因。
# ==============================================================================

set -euo pipefail

# ------------------------------------------------------------------------------
# 1. 时间处理
# ------------------------------------------------------------------------------

# 函数: now_human
# 描述: 获取当前可读的时间戳
# 输出示例: 2026-04-04 14:30:05.123
now_human() {
    date +"%Y-%m-%d %H:%M:%S.%3N"
}

# ------------------------------------------------------------------------------
# 2. 日志文件装饰器 (Header & Footer)
# ------------------------------------------------------------------------------

# 函数: log_header
# 描述: 在日志文件开头写入启动元数据
# 参数: $1 - 日志文件路径 (必填)
#       $2 - 任务标题 (可选)
#       $3 - 执行的完整命令 (可选)
log_header() {
    local file="${1:?错误: 未指定日志文件}"
    local title="${2:-未命名任务}"
    local cmd="${3:-未知命令}"

    # 使用大括号包裹写入逻辑，减少多次打开文件的开销
    {
        echo "================================================================"
        echo "  START TIME : $(now_human)"
        echo "  TITLE      : $title"
        echo "  COMMAND    : $cmd"
        echo "----------------------------------------------------------------"
    } >> "$file"
}

# 函数: log_footer
# 描述: 在日志文件末尾写入结束元数据和退出状态码
# 参数: $1 - 日志文件路径 (必填)
#       $2 - 退出状态码 (可选，默认为 0)
log_footer() {
    local file="${1:?错误: 未指定日志文件}"
    local ret="${2:-0}"

    {
        echo "----------------------------------------------------------------"
        echo "  EXIT CODE  : $ret"
        echo "  END TIME   : $(now_human)"
        echo "================================================================"
        echo -e "\n\n" # 留出空行方便追加下一次记录
    } >> "$file"
}

# ------------------------------------------------------------------------------
# 3. 辅助功能 (扩展建议)
# ------------------------------------------------------------------------------

# 函数: log_mark_error
# 描述: 如果发生错误，在日志中插入显眼的错误标记
log_mark_error() {
    local file="${1:?file required}"
    local msg="${2:-发生未知异常}"
    echo -e "\n[!] ERROR DETECTED at $(now_human)\n[!] MSG: $msg\n" >> "$file"
}